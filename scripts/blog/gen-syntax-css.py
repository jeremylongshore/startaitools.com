#!/usr/bin/env python3
"""Generate assets/css/syntax.css: code highlighting scoped to the site's light and dark themes.

Hugo's highlighter emits CSS classes (markup.highlight noClasses = false), so the colours
live in this stylesheet instead of inline styles. Light uses Chroma's "github" and dark uses
"github-dark": every visible token in both palettes is at least 4.5:1 against the site's code
box (the previous "friendly" palette fell to 2.4:1 for constants and string interpolation).
Chroma's own backgrounds are dropped so the site's code box (custom.css `pre`) shows through.

Scopes mirror assets/css/tokens.css and the early theme script in layouts/partials/header.html:
  light: [data-theme="light"], and @media (prefers-color-scheme: light) :root:not([data-theme])
  dark:  [data-theme="dark"], and :root:not([data-theme]) (the no-JavaScript default)

Usage: python3 scripts/blog/gen-syntax-css.py [--check]   (needs the hugo binary)
"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "assets/css/syntax.css"
LIGHT_STYLE, DARK_STYLE = "github", "github-dark"
RULE = re.compile(r"^(?:/\*.*?\*/\s*)?([^{}]+)\{([^}]*)\}\s*$")


def chroma(style: str) -> str:
    return subprocess.run(
        ["hugo", "gen", "chromastyles", f"--style={style}"],
        cwd=ROOT, capture_output=True, text=True, check=True,
    ).stdout


def scoped(css: str, scopes: list[str]) -> list[str]:
    """Prefix every Chroma rule with each scope; drop Chroma's own backgrounds."""
    rules = []
    for line in css.splitlines():
        match = RULE.match(line.strip())
        if not match:
            continue
        selectors = [s.strip() for s in match.group(1).split(",")]
        body = match.group(2).strip()
        if selectors == [".bg"]:
            continue  # the site's code box supplies the background
        if selectors == [".chroma"]:
            body = re.sub(r"background-color:[^;]*;?", "", body).strip()
            if not body:
                continue
        prefixed = ", ".join(f"{scope} {sel}" for scope in scopes for sel in selectors)
        rules.append(f"{prefixed} {{ {body} }}")
    return rules


def render(light_css: str, dark_css: str) -> str:
    dark = scoped(dark_css, ['[data-theme="dark"]', ":root:not([data-theme])"])
    light = scoped(light_css, ['[data-theme="light"]'])
    auto_light = scoped(light_css, [":root:not([data-theme])"])
    return "\n".join([
        "/* Generated by scripts/blog/gen-syntax-css.py; do not edit by hand.",
        f"   Light: chroma {LIGHT_STYLE}. Dark: chroma {DARK_STYLE}.",
        "   Backgrounds come from custom.css. */",
        "",
        "/* Dark (default, and the no-JavaScript fallback) */",
        *dark,
        "",
        "/* Light */",
        *light,
        "",
        "/* No JavaScript, OS prefers light */",
        "@media (prefers-color-scheme: light) {",
        *(f"  {rule}" for rule in auto_light),
        "}",
        "",
    ])


def main(argv: list[str]) -> int:
    text = render(chroma(LIGHT_STYLE), chroma(DARK_STYLE))
    if "--check" in argv:
        if OUTPUT.read_text() != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; re-run without --check", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
